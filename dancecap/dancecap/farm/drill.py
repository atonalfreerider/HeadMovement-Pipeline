"""farm drill: a cheap, REAL end-to-end proof of the farm on the real volume (FARM.md section 10, change log "drill").

    python -m dancecap.farm drill setup     the scratch dance `farmdrill` (takes/farmdrill.toml, its world pointer, camera spans)
    python -m dancecap.farm drill make      slice larissa_kadu_38's prepared MAMMA inputs into the drill chunks + their job specs
    python -m dancecap.farm drill verify    compare the pulled fit / refine with larissa_kadu_38's existing result on the same frames
    python -m dancecap.farm drill cleanup   archive the scratch dance (takes/farmdrill.toml, worlds/farmdrill/, work/farmdrill*): moved, never deleted

WHY A SCRATCH DANCE. The farm keys everything (state.json, coverage.json, the single watcher, pod names, the monitor) by dance.
The real dance larissa_kadu_full is being worked on by other sessions (fit_full fits, the stitch); a drill that registered chunks in
ITS state.json could be picked up by a planner / the `final` stitch job, and its watcher would collide with theirs. `farmdrill` has the
same 30 Hz lattice as larissa_kadu_38 (k = frame i of the 38 s span) and the SAME world package (same world id, same sha256, the volume's
copy is used), but its own state, coverage, watcher and pods, so the drill cannot disturb anything and the Pipeline Monitor shows it as a
defrag map of its own (`PipelineMonitor.exe --dance farmdrill`).

THE CHUNKS. Three real jobs of kind `full` (fit + refine; the front end is "done": prepared inputs exist), windows cut out of the 38 s
take's prepared inputs (every array of ma_2d / ma_cap/gt has the frame axis first, so a window is an exact slice; the cameras,
landmarks and sync are the real ones):
    dra  40 frames at 38 s frame 510     drb  40 frames at frame 810     drs  300 frames at frame 90 (the 4090 speed measurement)
Their outputs must match the existing 38 s fit (work/larissa_kadu_38/smplx, smplx_rf2_noslip) on the same frames: that is the
correctness check of the pod environment on the volume. `drill verify` writes work/farmdrill/farm/drill/verify.json.
"""
from __future__ import annotations

import argparse
import json
import shutil
import time
from pathlib import Path

import numpy as np

from . import farm_dir, work_dir, worlds_data, worlds_tracked
from .state import State, atomic_write_json, now_iso, read_json
from ..take import PACKAGE_ROOT

DRILL = "farmdrill"
REAL = "larissa_kadu_full"
REF = "larissa_kadu_38"
# id -> (first frame of the 38 s span, frames). Cell edges are multiples of 30: drs fills cells 3..12 exactly, dra / drb one cell + 10 frames.
WINDOWS = {"drs": (90, 300), "dra": (510, 40), "drb": (810, 40), "drc": (1000, 40),   # drc: the survivability round (a third check window)
           "dr9": (100, 900)}   # dr9: a REAL 30-s chunk (900 frames): the 4090 speed measured, not extrapolated
TOML_TEMPLATE = '''# GENERATED by `python -m dancecap.farm drill setup`: the scratch dance of the farm drill (FARM.md change log, drill).
# Same 30 Hz lattice as larissa_kadu_38 (k = frame i of the 38 s span) and the SAME world package as larissa_kadu_full; its own
# farm state / coverage / watcher / pods. Safe to delete (`drill cleanup`); nothing real depends on it.
name = "{name}"
source_dir = "../../dances/Larissa-Kadu-demo"
alignment = "../../prototype/larissa_kadu/alignment_studio.json"
exclude = ["08"]
window = [30.151176844227862, 68.4]

[timeline]
anchor = 30.151176844227862
hz = 30.0
k = [0, 1147]

[sync]
required = true

[world]
dance = "{name}"
id = "{world_id}"
pose_id = "{pose_id}"
role = "drill"
'''


def _say(msg: str) -> None:
    print(f"[drill] {msg}", flush=True)


# ------------------------------------------------------------------------------------------------ setup


def setup() -> dict:
    """The scratch dance: TOML, a copy of the real dance's CURRENT world pointer + manifest (tracked, ~100 KB), the data tree's manifest +
    shared/ (86 KB; ref/ stays out: the pods use the volume's copy), the camera spans. Idempotent."""
    cur = read_json(worlds_tracked(REAL) / "CURRENT.json", None)
    if not cur:
        raise SystemExit(f"{REAL} has no published world; nothing to share")
    wid = cur["world_id"]
    toml = PACKAGE_ROOT / "takes" / f"{DRILL}.toml"
    toml.write_text(TOML_TEMPLATE.format(name=DRILL, world_id=wid, pose_id=cur["pose_id"]), encoding="utf-8")
    wt = worlds_tracked(DRILL)
    (wt / wid).mkdir(parents=True, exist_ok=True)
    shutil.copy2(worlds_tracked(REAL) / wid / "manifest.json", wt / wid / "manifest.json")
    shutil.copy2(worlds_tracked(REAL) / "CURRENT.json", wt / "CURRENT.json")
    wd = worlds_data(DRILL) / wid
    wd.mkdir(parents=True, exist_ok=True)
    src = worlds_data(REAL) / wid
    shutil.copy2(src / "manifest.json", wd / "manifest.json")
    if (wd / "shared").exists():
        shutil.rmtree(wd / "shared")
    shutil.copytree(src / "shared", wd / "shared")
    fd = farm_dir(DRILL)
    fd.mkdir(parents=True, exist_ok=True)
    cam = farm_dir(REAL) / "cameras.json"
    if cam.exists():
        shutil.copy2(cam, fd / "cameras.json")
    out = {"dance": DRILL, "toml": str(toml), "world_id": wid, "pose_id": cur["pose_id"], "data": str(wd)}
    _say(f"scratch dance {DRILL} ready (world {wid})")
    return out


def cleanup() -> dict:
    """Take the drill out of the way WITHOUT deleting anything: the scratch dance's tracked-path files (takes/farmdrill.toml,
    worlds/farmdrill/) and its work dirs (work/farmdrill*, work/worlds/farmdrill) are MOVED to work/pipeline/archive/<date>/farmdrill_drill/.
    Reason: the Pipeline Monitor lists every dance with a farm directory, newest first, so a left-over drill would open as the default view,
    and git would see untracked scaffolding. `drill setup` recreates what the farm needs to run it again."""
    dest = PACKAGE_ROOT / "work" / "pipeline" / "archive" / time.strftime("%Y-%m-%d") / "farmdrill_drill"
    dest.mkdir(parents=True, exist_ok=True)
    work = PACKAGE_ROOT / "work"
    todo = [PACKAGE_ROOT / "takes" / f"{DRILL}.toml", worlds_tracked(DRILL), worlds_data(DRILL)]
    todo += sorted(p for p in work.glob(f"{DRILL}*") if p.is_dir())
    moved = []
    for p in todo:
        if not p.exists():
            continue
        rel = p.relative_to(PACKAGE_ROOT).as_posix().replace("/", "__")
        target = dest / rel
        if target.exists():
            target = dest / f"{rel}.{int(time.time())}"
        shutil.move(str(p), str(target))
        moved.append(f"{p} -> {target}")
    return {"archived_to": str(dest), "moved": moved}


# ------------------------------------------------------------------------------------------------ slicing the prepared inputs


def _slice_npz(src: Path, dst: Path, a: int, b: int, T: int, scalars: dict | None = None) -> None:
    z = np.load(src, allow_pickle=False)
    out = {}
    for k in z.files:
        v = z[k]
        out[k] = v[a:b] if v.ndim >= 1 and v.shape[0] == T else v
    for k, v in (scalars or {}).items():
        if k in out:
            out[k] = np.asarray(v, dtype=out[k].dtype)
    dst.parent.mkdir(parents=True, exist_ok=True)
    np.savez_compressed(dst, **out)


def slice_take(cid: str, start: int, n: int) -> dict:
    """work/farmdrill_<cid>/mamma/ = frames start..start+n-1 of larissa_kadu_38's prepared set c8 (the full camera set)."""
    src = work_dir(REF) / "mamma"
    prep = json.loads((src / "prepare.json").read_text(encoding="utf-8"))
    T = int(prep["grid"]["T"])
    a, b = int(start), int(start + n)
    if not 0 <= a < b <= T:
        raise SystemExit(f"window {a}..{b} is outside the 38 s grid (T={T})")
    take = f"{DRILL}_{cid}"
    dst = work_dir(take) / "mamma"
    if dst.exists():
        shutil.rmtree(dst)
    s = prep["sets"]["c8"]
    old_seq, seq = s["seq"], f"{take}_c8"
    t = prep["grid"]["t"][a:b]
    grid = {**{k: v for k, v in prep["grid"].items() if k not in ("t", "t0", "T")}, "t0": t[0], "T": n, "t": t}
    new = {"take": take, "created": now_iso(), "world_frame": prep["world_frame"], "grid": grid, "sync": prep.get("sync"),
           "ma_2d": {}, "config": prep["config"], "config_overrides": prep.get("config_overrides"),
           "base_config": prep.get("base_config"),
           "sets": {"c8": {"seq": seq, "cams": s["cams"], "inputs": s["inputs"]}},
           "eval": {"seq": seq, "cams": s["cams"]},
           "drill": {"slice_of": REF, "frames": [a, b], "note": "exact slice of the 38 s prepared inputs (farm drill)"}}
    (dst).mkdir(parents=True, exist_ok=True)
    (dst / "prepare.json").write_text(json.dumps(new, indent=1), encoding="utf-8")
    shutil.copy2(src / prep["config"], dst / prep["config"])
    cams = list(s["cams"])
    for c in cams:
        _slice_npz(src / "ma_2d" / old_seq / f"cam{c}.npz", dst / "ma_2d" / seq / f"cam{c}.npz", a, b, T)
        _slice_npz(src / "ma_cap" / old_seq / "gt" / f"cam{c}.npz", dst / "ma_cap" / seq / "gt" / f"cam{c}.npz", a, b, T,
                   scalars={"frame_start": 0, "frame_end": n})
    _slice_npz(src / "ma_cap" / old_seq / "gt" / "global.npz", dst / "ma_cap" / seq / "gt" / "global.npz", a, b, T,
               scalars={"frames_len": n, "frame_start": 0, "frame_end": n})
    g = np.load(dst / "ma_cap" / seq / "gt" / "global.npz")
    g2 = {k: g[k] for k in g.files}
    g2["seq_name"] = np.asarray(seq)
    np.savez_compressed(dst / "ma_cap" / seq / "gt" / "global.npz", **g2)
    return {"take": take, "frames": [a, b], "cams": cams, "grid_t0": t[0]}


# ------------------------------------------------------------------------------------------------ make


def make(ids: list[str] | None = None) -> dict:
    """Slice the inputs, register the chunks in the drill's state.json and write their job specs (`farm queue` uploads them)."""
    from . import chunks as C
    from . import world as W
    from .timeline import DanceSpec
    spec = DanceSpec.load(DRILL)
    w = W.load(DRILL)
    st = State(DRILL)
    code = C.code_info()
    made = {}
    chunks = []
    for cid in ids or list(WINDOWS):
        start, n = WINDOWS[cid]
        info = slice_take(cid, start, n)
        k0, k1 = start, start + n - 1
        ch = C.Chunk(id=cid, k0=k0, k1=k1, core_k0=k0, core_k1=k1, overlap_k=0, kind="full", cams=info["cams"], world_id=w.id,
                     origin="drill", take=info["take"], stages_done=["front"])
        ch.estimate = C.estimate(ch, spec)
        ch.priority = ch.estimate["total_min"]
        job = C.build_job(ch, spec, w, code=code)
        if cid == "drs":   # the speed measurement: generous step timeouts (a 4090 is ~2x an A100), still bounded
            for s in job["steps"]:
                if s["name"] == "fit":
                    s["timeout_min"] = 75.0
                elif s["name"] == "refine":
                    s["timeout_min"] = 15.0
            job["max_minutes"] = 100.0
        job["drill"] = {"slice_of": REF, "frames": [start, start + n], "purpose": "pod environment check" if n < 100 else "4090 speed"}
        p = C.write_job(job, DRILL)
        chunks.append(ch.to_dict())
        made[cid] = {"take": info["take"], "frames": n, "job": str(p), "inputs": [(i["path"], i.get("bytes")) for i in job["inputs"]],
                     "steps": [s["name"] for s in job["steps"]], "est_min": ch.estimate["total_min"]}
    st.put_chunks(chunks, replace_planned=False)
    for cid in made:
        st.set_job(cid, chunk=cid, kind="full", status="planned", written=now_iso(), spec=str(farm_dir(DRILL) / "jobs" / f"{cid}.json"))
    st.event("drill", f"drill chunks made: {', '.join(made)}")
    atomic_write_json(farm_dir(DRILL) / "drill" / "made.json", {"created": now_iso(), "windows": WINDOWS, "chunks": made})
    return made


def make_mismatch() -> dict:
    """`drx`: a job that must be REFUSED. dra's spec with a tampered world_sha256 and a harmless step: the worker's world check
    (FARM.md section 3) has to fail it before any step runs, and the watcher has to treat it as a failed chunk (re-queue, then give up)."""
    src = farm_dir(DRILL) / "jobs" / "dra.json"
    job = json.loads(src.read_text(encoding="utf-8"))
    job.update(id="drx", take=f"{DRILL}_drx", world_sha256="0" * 8 + job["world_sha256"][8:], stages=["fit"], inputs=[], outputs=[],
               steps=[{"name": "never", "cmd": "echo THIS MUST NOT RUN", "timeout_min": 1, "optional": False}], priority=0.1, retries=1,
               max_minutes=5.0, kind="analyse", needs_gpu=False,   # a CPU pod takes it: the world check comes before any step
               drill={"purpose": "deliberate world-hash mismatch: the worker must refuse it"})
    job.pop("min_vram_gb", None)
    job["chunk"] = {**job["chunk"], "id": "drx", "take": f"{DRILL}_drx"}
    job.pop("estimate", None)
    from . import chunks as C
    p = C.write_job(job, DRILL)
    State(DRILL).set_job("drx", kind="analyse", status="planned", written=now_iso(), spec=str(p))
    return {"drx": {"job": str(p), "world_sha256": job["world_sha256"]}}


# ------------------------------------------------------------------------------------------------ verify


def _joint_err_mm(a: np.ndarray, b: np.ndarray) -> np.ndarray:
    """(T, J) euclidean distance in millimetres between two (T, J, 3) joint arrays (metres in, the contract's unit)."""
    return np.linalg.norm(a - b, axis=-1) * 1000.0


def _compare(got_dir: Path, ref_dir: Path, start: int, n: int, trim: int = 0) -> dict:
    out = {}
    for role in ("lead", "follow"):
        g = np.load(got_dir / f"{role}.npz", allow_pickle=False)
        r = np.load(ref_dir / f"{role}.npz", allow_pickle=False)
        sl = slice(start, start + n)
        tg, tr = np.asarray(g["t"], float), np.asarray(r["t"], float)[sl]
        if len(tg) != n or float(np.abs(tg - tr).max()) > 1e-6:
            out[role] = {"error": f"time axes differ: got {len(tg)} frames, window {n}; max dt {float(np.abs(tg[:n] - tr[:len(tg)]).max()):.2e}"}
            continue
        i0, i1 = trim, n - trim
        body = slice(0, 22)
        e = _joint_err_mm(np.asarray(g["joints"], float)[i0:i1, body], np.asarray(r["joints"], float)[sl][i0:i1, body])
        pel = np.linalg.norm(np.asarray(g["joints"], float)[i0:i1, 0] - np.asarray(r["joints"], float)[sl][i0:i1, 0], axis=-1) * 1000
        rp_g = np.asarray(g["reproj_px"], float)[i0:i1]
        rp_r = np.asarray(r["reproj_px"], float)[sl][i0:i1]
        out[role] = {"frames": int(i1 - i0), "joint_mm_median": round(float(np.median(e)), 2), "joint_mm_p95": round(float(np.percentile(e, 95)), 2),
                     "joint_mm_max": round(float(e.max()), 2), "pelvis_mm_median": round(float(np.median(pel)), 2),
                     "reproj_px_median_got": round(float(np.nanmedian(rp_g)), 3), "reproj_px_median_ref": round(float(np.nanmedian(rp_r)), 3),
                     "betas_maxabs_diff": round(float(np.abs(np.asarray(g["betas"]) - np.asarray(r["betas"])).max()), 6)}
    return out


# acceptance: independent MAMMA runs of the same frames differ by ~1-3 cm (mamma_chunks.py: seam noise); a broken environment (wrong CUDA
# kernels, unpinned betas, wrong frame / camera order) differs by decimetres or in the reprojection
TOL = {"fit_joint_mm_median": 30.0, "fit_joint_mm_p95": 90.0, "refine_joint_mm_median": 30.0, "reproj_ratio": 1.25, "reproj_slack_px": 1.0}


def verify(ids: list[str] | None = None) -> dict:
    res = {"created": now_iso(), "tolerances": TOL, "windows": {}}
    ok_all = True
    for cid in ids or list(WINDOWS):
        start, n = WINDOWS[cid]
        take = work_dir(f"{DRILL}_{cid}")
        r: dict = {"frames": [start, start + n]}
        for what, got_sub, ref_sub, trim in (("fit", "smplx", "smplx", 0), ("refined", "smplx_rf2_noslip", "smplx_rf2_noslip", 0),
                                              ("refined_interior", "smplx_rf2_noslip", "smplx_rf2_noslip", min(10, n // 4))):
            if not (take / got_sub / "lead.npz").exists():
                r[what] = {"error": f"{take / got_sub} not pulled yet"}
                ok_all = False
                continue
            r[what] = _compare(take / got_sub, work_dir(REF) / ref_sub, start, n, trim)
        passed = True
        why = []
        for role in ("lead", "follow"):
            f = (r.get("fit") or {}).get(role) or {}
            if "joint_mm_median" not in f:
                passed = False
                why.append(f"fit {role}: {f.get('error', 'missing')}")
                continue
            if f["joint_mm_median"] > TOL["fit_joint_mm_median"]:
                passed = False
                why.append(f"fit {role}: joint median {f['joint_mm_median']} mm > {TOL['fit_joint_mm_median']}")
            if f["joint_mm_p95"] > TOL["fit_joint_mm_p95"]:
                passed = False
                why.append(f"fit {role}: joint p95 {f['joint_mm_p95']} mm > {TOL['fit_joint_mm_p95']}")
            if f["reproj_px_median_got"] > TOL["reproj_ratio"] * f["reproj_px_median_ref"] + TOL["reproj_slack_px"]:
                passed = False
                why.append(f"fit {role}: reprojection {f['reproj_px_median_got']} px vs reference {f['reproj_px_median_ref']} px")
            if f["betas_maxabs_diff"] > 1e-3:
                why.append(f"fit {role}: betas differ from the reference by {f['betas_maxabs_diff']} (info: the reference merged per-chunk betas)")
            ri = ((r.get("refined_interior") or {}).get(role)) or {}
            if "joint_mm_median" in ri and ri["joint_mm_median"] > TOL["refine_joint_mm_median"]:
                passed = False
                why.append(f"refined {role}: interior joint median {ri['joint_mm_median']} mm > {TOL['refine_joint_mm_median']}")
        r["pass"], r["why"] = passed, why
        ok_all &= passed
        res["windows"][cid] = r
    res["pass"] = ok_all
    atomic_write_json(farm_dir(DRILL) / "drill" / "verify.json", res)
    return res


# ------------------------------------------------------------------------------------------------ CLI


def cmd_drill(a) -> int:
    act = a.action
    ids = [x for x in (a.ids or "").split(",") if x] or None
    if act == "setup":
        out = setup()
    elif act == "make":
        out = make_mismatch() if ids == ["drx"] else make(ids)
    elif act == "verify":
        out = verify(ids)
    elif act == "cleanup":
        out = cleanup()
    else:
        return 2
    print(json.dumps(out, indent=1, default=str))
    return 0 if act != "verify" or out.get("pass") else 1


def register(sub) -> None:
    p = sub.add_parser("drill", help="the end-to-end drill on the real volume (scratch dance `farmdrill`): setup | make | verify | cleanup")
    p.add_argument("action", choices=("setup", "make", "verify", "cleanup"))
    p.add_argument("--ids", help="comma list of drill chunk ids (default: all)")
    p.set_defaults(func=cmd_drill)
